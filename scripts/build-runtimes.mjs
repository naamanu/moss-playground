// Prepare what the playground needs at runtime:
//
// 1. public/runtime/core.js and public/runtime/rhizoid.js: standalone ES
//    modules that programs run in the preview frame import. rhizoid.js imports
//    core.js, so a program and Rhizoid share one core runtime instance.
// 2. runtime/sources.generated.ts: the Rhizoid library's Moss sources (so the
//    in-browser compiler can resolve `open Rhizoid`) and the example programs.
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as esbuild from "esbuild";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "public/runtime");
mkdirSync(out, { recursive: true });

// Every core runtime module, re-exported from one bundle.
await esbuild.build({
  stdin: {
    contents: ["index", "effect", "pmap", "prelude", "task"].map((m) => `export * from "mosslang/runtime/${m}.ts";`).join("\n"),
    resolveDir: root,
    loader: "ts",
  },
  bundle: true,
  format: "esm",
  target: "es2022",
  minify: true,
  outfile: join(out, "core.js"),
});

// Rhizoid's runtime, importing the core runtime from ./core.js.
await esbuild.build({
  entryPoints: [join(root, "node_modules/rhizoid/runtime/index.ts")],
  bundle: true,
  format: "esm",
  target: "es2022",
  minify: true,
  outfile: join(out, "rhizoid.js"),
  plugins: [
    {
      name: "core-external",
      setup(b) {
        b.onResolve({ filter: /^mosslang\/runtime/ }, () => ({ path: "./core.js", external: true }));
      },
    },
  ],
});

const mossFiles = (dir) =>
  Object.fromEntries(
    readdirSync(dir)
      .filter((f) => f.endsWith(".moss"))
      .sort()
      .map((f) => [f.slice(0, -".moss".length), readFileSync(join(dir, f), "utf8")]),
  );
const rhizoid = Object.fromEntries(
  Object.entries(mossFiles(join(root, "node_modules/rhizoid/src"))).map(([f, s]) => [f[0].toUpperCase() + f.slice(1), s]),
);
const examples = mossFiles(join(root, "examples"));
writeFileSync(
  join(root, "runtime/sources.generated.ts"),
  `// Generated by scripts/build-runtimes.mjs. Do not edit.\n\n` +
    `/** Rhizoid's Moss modules, by module name. */\nexport const RHIZOID: Record<string, string> = ${JSON.stringify(rhizoid, null, 2)};\n\n` +
    `/** Example programs, by file name (without .moss). */\nexport const EXAMPLES: Record<string, string> = ${JSON.stringify(examples, null, 2)};\n`,
);
console.log("built public/runtime/{core,rhizoid}.js and runtime/sources.generated.ts");
