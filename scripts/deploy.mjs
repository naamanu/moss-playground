// Publish the built playground (dist/) to the public GitHub Pages repo.
// The source stays in this (private) repo; the site repo holds only build output.
//
//   npm run deploy        (builds first)
import { execFileSync } from "node:child_process";
import { cpSync, existsSync, mkdtempSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const SITE_REPO = "https://github.com/naamanu/moss-playground-site.git";
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dist = join(root, "dist");
if (!existsSync(join(dist, "index.html"))) throw new Error("dist/ is missing: run `npm run build` first");

const git = (cwd, ...args) => execFileSync("git", args, { cwd, stdio: ["ignore", "pipe", "inherit"], encoding: "utf8" }).trim();
const source = git(root, "rev-parse", "--short", "HEAD");
const dirty = git(root, "status", "--porcelain") !== "";

const work = mkdtempSync(join(tmpdir(), "moss-site-"));
try {
  git(work, "clone", "--quiet", "--depth", "1", SITE_REPO, ".");
  for (const f of readdirSync(work)) if (f !== ".git") rmSync(join(work, f), { recursive: true, force: true });
  cpSync(dist, work, { recursive: true });
  writeFileSync(join(work, ".nojekyll"), ""); // serve files as-is
  writeFileSync(
    join(work, "README.md"),
    "# Moss playground (built site)\n\nBuild output of the Moss playground, served by GitHub Pages.\nGenerated by `npm run deploy`; don't edit by hand.\n",
  );
  git(work, "add", "-A");
  if (git(work, "status", "--porcelain") === "") {
    console.log("site is already up to date");
  } else {
    git(work, "commit", "--quiet", "-m", `Deploy playground ${source}${dirty ? " (with uncommitted changes)" : ""}`);
    git(work, "push", "--quiet", "origin", "HEAD");
    console.log(`deployed playground ${source} to ${SITE_REPO}`);
  }
} finally {
  rmSync(work, { recursive: true, force: true });
}
